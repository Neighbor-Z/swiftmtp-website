function setLanguage(lang) {
  const dict = i18n[lang] || i18n['en'];

  // Find all elements with a data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  // Update App Store badges
  const appStoreBadges = {
    'ar': 'assets/Download_on_the_Mac_App_Store_Badge_AR_RGB_blk_102417.svg',
    'zh-Hans': 'assets/Download_on_the_Mac_App_Store_Badge_CNSC_RGB_blk_092917.svg',
    'zh-Hant': 'assets/Download_on_the_Mac_App_Store_Badge_CNTC_RGB_blk_100217.svg',
    'es': 'assets/Download_on_the_Mac_App_Store_Badge_ES_RGB_blk_100217.svg',
    'ja': 'assets/Download_on_the_Mac_App_Store_Badge_JP_RGB_blk_100317.svg',
    'default': 'assets/Download_on_the_Mac_App_Store_Badge_US-UK_RGB_blk_092917.svg'
  };

  const badgeSrc = appStoreBadges[lang] || appStoreBadges['default'];
  const badgeHero = document.getElementById('appstore-badge-hero');
  const badgeCta = document.getElementById('appstore-badge-cta');
  
  if (badgeHero) badgeHero.src = badgeSrc;
  if (badgeCta) badgeCta.src = badgeSrc;
}

function initI18n() {
  const langMenu = document.getElementById('lang-menu');
  const langToggle = document.getElementById('lang-toggle');
  const langItems = document.querySelectorAll('.dropdown-item');
  const langLabel = document.getElementById('lang-label');
  
  let defaultLang = 'en';

  const userLang = (navigator.language || navigator.userLanguage).toLowerCase();
  if (userLang.startsWith('zh')) {
    if (userLang.includes("tw") || userLang.includes("hk") || userLang.includes("hant")) {
      defaultLang = "zh-Hant";
    } else {
      defaultLang = "zh-Hans";
    }
  } else if (userLang.startsWith('ja')) {
    defaultLang = 'ja';
  } else if (userLang.startsWith('es')) {
    defaultLang = 'es';
  } else if (userLang.startsWith('de')) {
    defaultLang = 'de';
  } else if (userLang.startsWith('fr')) {
    defaultLang = 'fr';
  } else if (userLang.startsWith('uk')) {
    defaultLang = 'uk';
  } else if (userLang.startsWith('it')) {
    defaultLang = 'it';
  } else if (userLang.startsWith('ko')) {
    defaultLang = 'ko';
  } else if (userLang.startsWith('tr')) {
    defaultLang = 'tr';
  } else if (userLang.startsWith('vi')) {
    defaultLang = 'vi';
  } else if (userLang.startsWith('ar')) {
    defaultLang = 'ar';
  }

  function updateDropdown(val) {
    langItems.forEach(el => {
      if (el.getAttribute('data-value') === val) {
        el.classList.add('active');
        langLabel.textContent = el.textContent;
      } else {
        el.classList.remove('active');
      }
    });
  }

  updateDropdown(defaultLang);
  setLanguage(defaultLang);

  // Dropdown interactions
  langToggle.addEventListener('click', (e) => {
    e.stopPropagation();
    const isOpen = langMenu.classList.contains('open');
    if (isOpen) {
      langMenu.classList.remove('open');
      langToggle.setAttribute('aria-expanded', 'false');
    } else {
      langMenu.classList.add('open');
      langToggle.setAttribute('aria-expanded', 'true');
    }
  });

  window.addEventListener('click', () => {
    langMenu.classList.remove('open');
    langToggle.setAttribute('aria-expanded', 'false');
  });

  langItems.forEach(item => {
    item.addEventListener('click', (e) => {
      e.stopPropagation();
      const val = item.getAttribute('data-value');
      updateDropdown(val);
      setLanguage(val);
      langMenu.classList.remove('open');
      langToggle.setAttribute('aria-expanded', 'false');
    });
  });
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
